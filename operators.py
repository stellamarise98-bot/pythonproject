#Arithmetic operators - simple calculations

x = 90
y = 5
print(x+y)
print(x-y)
print(x*y)
print(x/y)
print(x%y) #modulus - returns remainder after division

print(x**y)
print(x//y)
#comparison operators
num1 = 45
num2 = 20
print(num1 < num2)
print(num1 > num2)
print(num1 == num2)
print(num1 != num2)
print(num1 >= num2)

print(num1 <= num2)

print(num1 != num2)


#assignment operators - Assign/store values in variable
number = 80
print(number)

#operator precedence
number += 2
print(number)

#logical operators - and,or,not(&&,||,)
print( 100==50 and 60 < 80)
print( 100==50 or 60 < 80)
print( not(100==50 and 60 < 80 ) )
